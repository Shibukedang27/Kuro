#!/usr/bin/env python3
"""Freeze freestanding formatter assembly into Kuro Text (development only).

Requires Clang 18. Generated programs and Kuro generators do not invoke C or
this script. Review regenerated instruction changes when changing Clang.
"""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess

ROOT = Path(__file__).resolve().parents[1]
START = "# BEGIN FROZEN ARM64 DECIMAL FORMATTER\n"
END = "# END FROZEN ARM64 DECIMAL FORMATTER\n"


def frozen_action():
    source = ROOT / "self_host" / "decimal_formatter.c"
    result = subprocess.run([
        "clang", "-target", "arm64-apple-macos11", "-Os", "-S", "-x", "c",
        "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
        "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
        "-fno-vectorize", "-fno-slp-vectorize", "-fno-jump-tables",
        str(source), "-o", "-",
    ], check=True, capture_output=True, text=True)
    assembly = "\n.section __TEXT,__text\n_kuro_print_float:\n"
    assembly += (
        "    sub sp, sp, #80\n    stp x29, x30, [sp, #64]\n"
        "    mov x1, sp\n    bl _kuro_decimal_format\n"
        "    mov w2, w0\n    mov x1, sp\n    mov x0, #1\n"
        "    mov x16, #4\n    svc #0x80\n"
        "    ldp x29, x30, [sp, #64]\n    add sp, sp, #80\n    ret\n"
    )
    # Filename and platform metadata are not part of the formatter contract.
    for line in result.stdout.splitlines():
        if line.strip().startswith((".build_version", ".file", ".subsections_via_symbols")):
            continue
        assembly += line.split(";", 1)[0].rstrip() + "\n"
    header = START + "# Generated by scripts/freeze_decimal_formatter.py (Clang 18).\n"
    header += "# C source SHA256: " + hashlib.sha256(source.read_bytes()).hexdigest() + "\n"
    header += "Action NativeEmitArmDecimalFormatter;\n"
    chunk = ""
    for line in assembly.splitlines(keepends=True):
        if len(chunk) + len(line) > 4096:
            header += "    NativeOut = NativeOut + " + json.dumps(chunk) + ";\n"
            chunk = ""
        chunk += line
    if chunk:
        header += "    NativeOut = NativeOut + " + json.dumps(chunk) + ";\n"
    return header + "Done.\n" + END


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "self_host" / "native_codegen.kuro"
    text = path.read_text()
    generated = frozen_action()
    if START in text:
        before, rest = text.split(START, 1)
        _, after = rest.split(END, 1)
        updated = before + generated + after
    else:
        updated = text.replace("Action NativeEmitDecimalFormatter;\n", generated + "\nAction NativeEmitDecimalFormatter;\n", 1)
    if args.check:
        if text != updated:
            raise SystemExit("frozen ARM64 formatter is stale; regenerate with Clang 18")
    else:
        path.write_text(updated)


if __name__ == "__main__":
    main()
